SET LINESIZE 220 PAGESIZE 100 SERVEROUTPUT ON
COLUMN name FORMAT A12
COLUMN message FORMAT A140
PROMPT == try to synchronise the PDB
ALTER SESSION SET CONTAINER = XEPDB1;
EXEC DBMS_PDB.SYNC_PDB;
ALTER SESSION SET CONTAINER = CDB$ROOT;
PROMPT == re-open the PDB
ALTER PLUGGABLE DATABASE XEPDB1 CLOSE IMMEDIATE;
ALTER PLUGGABLE DATABASE XEPDB1 OPEN;
SELECT name, open_mode, restricted FROM v$pdbs;
SELECT name, status, message FROM pdb_plug_in_violations WHERE status <> 'RESOLVED';
EXIT
