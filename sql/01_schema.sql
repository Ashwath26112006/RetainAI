-- Staging table: raw CSV rows of the Kaggle/IBM Telco Customer Churn dataset (+ synthetic name/e-mail)
CREATE TABLE stg_telco (
  customer_id VARCHAR2(30), gender VARCHAR2(10), senior_citizen VARCHAR2(5), partner VARCHAR2(5),
  dependents VARCHAR2(5), tenure VARCHAR2(10), phone_service VARCHAR2(5), multiple_lines VARCHAR2(30),
  internet_service VARCHAR2(20), online_security VARCHAR2(30), online_backup VARCHAR2(30),
  device_protection VARCHAR2(30), tech_support VARCHAR2(30), streaming_tv VARCHAR2(30),
  streaming_movies VARCHAR2(30), contract VARCHAR2(30), paperless_billing VARCHAR2(5),
  payment_method VARCHAR2(40), monthly_charges VARCHAR2(20), total_charges VARCHAR2(20),
  churn VARCHAR2(5), full_name VARCHAR2(80), email VARCHAR2(120)
);

-- ---------------------------------------------------------------- lookup tables
CREATE TABLE contract_types (
  contract_type_id NUMBER(2)    CONSTRAINT pk_contract_types PRIMARY KEY,
  contract_name    VARCHAR2(30) NOT NULL CONSTRAINT uq_contract_name UNIQUE,
  term_months      NUMBER(3)    NOT NULL CONSTRAINT chk_term_months CHECK (term_months >= 1)
);

CREATE TABLE payment_methods (
  payment_method_id NUMBER(2)    CONSTRAINT pk_payment_methods PRIMARY KEY,
  method_name       VARCHAR2(40) NOT NULL CONSTRAINT uq_method_name UNIQUE,
  is_automatic      CHAR(1)      DEFAULT 'N' NOT NULL CONSTRAINT chk_pm_auto CHECK (is_automatic IN ('Y','N'))
);

CREATE TABLE plans (
  plan_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_plans PRIMARY KEY,
  plan_name        VARCHAR2(60) NOT NULL CONSTRAINT uq_plan_name UNIQUE,
  internet_service VARCHAR2(20) NOT NULL CONSTRAINT chk_plan_internet CHECK (internet_service IN ('DSL','Fiber optic','No')),
  phone_service    CHAR(1)      NOT NULL CONSTRAINT chk_plan_phone CHECK (phone_service IN ('Y','N')),
  base_price       NUMBER(8,2)  NOT NULL CONSTRAINT chk_plan_price CHECK (base_price > 0)
);

CREATE TABLE services (
  service_id       NUMBER(2)    CONSTRAINT pk_services PRIMARY KEY,
  service_name     VARCHAR2(40) NOT NULL CONSTRAINT uq_service_name UNIQUE,
  service_category VARCHAR2(20) NOT NULL
);

-- ---------------------------------------------------------------- core entities
CREATE SEQUENCE seq_customer START WITH 10001 INCREMENT BY 1 NOCACHE;

CREATE TABLE customers (
  customer_id    VARCHAR2(20)  CONSTRAINT pk_customers PRIMARY KEY,
  full_name      VARCHAR2(80)  NOT NULL,
  email          VARCHAR2(120) NOT NULL CONSTRAINT uq_customer_email UNIQUE,
  gender         VARCHAR2(10)  NOT NULL CONSTRAINT chk_cust_gender CHECK (gender IN ('Male','Female')),
  senior_citizen CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT chk_cust_senior CHECK (senior_citizen IN ('Y','N')),
  has_partner    CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT chk_cust_partner CHECK (has_partner IN ('Y','N')),
  has_dependents CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT chk_cust_dep CHECK (has_dependents IN ('Y','N')),
  signup_date    DATE          NOT NULL,
  status         VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL CONSTRAINT chk_cust_status CHECK (status IN ('ACTIVE','CHURNED')),
  created_at     DATE          DEFAULT SYSDATE NOT NULL
);

CREATE TABLE subscriptions (
  subscription_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_subscriptions PRIMARY KEY,
  customer_id       VARCHAR2(20) NOT NULL CONSTRAINT fk_sub_customer REFERENCES customers (customer_id),
  plan_id           NUMBER       NOT NULL CONSTRAINT fk_sub_plan REFERENCES plans (plan_id),
  contract_type_id  NUMBER(2)    NOT NULL CONSTRAINT fk_sub_contract REFERENCES contract_types (contract_type_id),
  payment_method_id NUMBER(2)    NOT NULL CONSTRAINT fk_sub_payment REFERENCES payment_methods (payment_method_id),
  paperless_billing CHAR(1)      DEFAULT 'N' NOT NULL CONSTRAINT chk_sub_paperless CHECK (paperless_billing IN ('Y','N')),
  start_date        DATE         NOT NULL,
  end_date          DATE,
  monthly_charge    NUMBER(8,2)  NOT NULL CONSTRAINT chk_sub_charge CHECK (monthly_charge >= 0),
  status            VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL CONSTRAINT chk_sub_status CHECK (status IN ('ACTIVE','CANCELLED','SUSPENDED')),
  cancel_reason     VARCHAR2(200),
  CONSTRAINT chk_sub_dates CHECK (end_date IS NULL OR end_date >= start_date)
);
-- business rule: a customer may hold at most ONE active subscription
CREATE UNIQUE INDEX uq_one_active_sub ON subscriptions (CASE WHEN status = 'ACTIVE' THEN customer_id END);
CREATE INDEX ix_sub_customer ON subscriptions (customer_id);

CREATE TABLE subscription_services (
  subscription_id NUMBER      NOT NULL CONSTRAINT fk_ss_sub REFERENCES subscriptions (subscription_id),
  service_id      NUMBER(2)   NOT NULL CONSTRAINT fk_ss_service REFERENCES services (service_id),
  added_on        DATE        DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_subscription_services PRIMARY KEY (subscription_id, service_id)
);

CREATE TABLE billing_records (
  bill_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_billing PRIMARY KEY,
  subscription_id NUMBER       NOT NULL CONSTRAINT fk_bill_sub REFERENCES subscriptions (subscription_id),
  bill_month      DATE         NOT NULL,
  amount          NUMBER(10,2) NOT NULL CONSTRAINT chk_bill_amount CHECK (amount >= 0),
  status          VARCHAR2(10) DEFAULT 'PENDING' NOT NULL CONSTRAINT chk_bill_status CHECK (status IN ('PENDING','PAID','OVERDUE')),
  due_date        DATE,
  paid_date       DATE,
  CONSTRAINT uq_bill_month UNIQUE (subscription_id, bill_month),
  CONSTRAINT chk_bill_paid CHECK (status = 'PAID' OR paid_date IS NULL)
);
CREATE INDEX ix_bill_status ON billing_records (status, bill_month);

CREATE TABLE support_tickets (
  ticket_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_tickets PRIMARY KEY,
  customer_id  VARCHAR2(20)  NOT NULL CONSTRAINT fk_ticket_customer REFERENCES customers (customer_id),
  category     VARCHAR2(20)  NOT NULL CONSTRAINT chk_ticket_cat CHECK (category IN ('BILLING','TECHNICAL','SERVICE','CANCELLATION','OTHER')),
  priority     VARCHAR2(10)  DEFAULT 'MEDIUM' NOT NULL CONSTRAINT chk_ticket_prio CHECK (priority IN ('LOW','MEDIUM','HIGH','URGENT')),
  status       VARCHAR2(12)  DEFAULT 'OPEN' NOT NULL CONSTRAINT chk_ticket_status CHECK (status IN ('OPEN','IN_PROGRESS','RESOLVED','CLOSED')),
  subject      VARCHAR2(200) NOT NULL,
  resolution   VARCHAR2(400),
  assigned_to  VARCHAR2(50),
  opened_at    DATE          NOT NULL,
  closed_at    DATE
);
CREATE INDEX ix_ticket_customer ON support_tickets (customer_id, status);

CREATE TABLE retention_campaigns (
  campaign_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_campaigns PRIMARY KEY,
  campaign_name   VARCHAR2(80)  NOT NULL CONSTRAINT uq_campaign_name UNIQUE,
  target_segment  VARCHAR2(20)  DEFAULT 'ANY' NOT NULL
                  CONSTRAINT chk_camp_segment CHECK (target_segment IN ('ANY','New','Standard','Loyal','Champion','At Risk')),
  offer           VARCHAR2(200) NOT NULL,
  discount_pct    NUMBER(5,2)   DEFAULT 0 NOT NULL CONSTRAINT chk_camp_disc CHECK (discount_pct BETWEEN 0 AND 100),
  start_date      DATE          NOT NULL,
  end_date        DATE          NOT NULL,
  status          VARCHAR2(10)  DEFAULT 'PLANNED' NOT NULL CONSTRAINT chk_camp_status CHECK (status IN ('PLANNED','ACTIVE','CLOSED')),
  CONSTRAINT chk_camp_dates CHECK (end_date >= start_date)
);

CREATE TABLE retention_actions (
  action_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_actions PRIMARY KEY,
  customer_id  VARCHAR2(20) NOT NULL CONSTRAINT fk_action_customer REFERENCES customers (customer_id),
  campaign_id  NUMBER       CONSTRAINT fk_action_campaign REFERENCES retention_campaigns (campaign_id),
  action_type  VARCHAR2(10) NOT NULL CONSTRAINT chk_action_type CHECK (action_type IN ('CALL','EMAIL','DISCOUNT','UPGRADE','WIN_BACK')),
  action_date  DATE         NOT NULL,
  outcome      VARCHAR2(12) DEFAULT 'PENDING' NOT NULL CONSTRAINT chk_action_outcome CHECK (outcome IN ('PENDING','ACCEPTED','DECLINED','NO_RESPONSE')),
  notes        VARCHAR2(400)
);
CREATE INDEX ix_action_customer ON retention_actions (customer_id);
CREATE INDEX ix_action_campaign ON retention_actions (campaign_id);

CREATE TABLE churn_scores (
  customer_id    VARCHAR2(20) CONSTRAINT pk_churn_scores PRIMARY KEY CONSTRAINT fk_score_customer REFERENCES customers (customer_id),
  rule_score     NUMBER(5,2)  NOT NULL CONSTRAINT chk_score_range CHECK (rule_score BETWEEN 0 AND 100),
  risk_band      VARCHAR2(10) NOT NULL CONSTRAINT chk_score_band CHECK (risk_band IN ('LOW','MEDIUM','HIGH')),
  segment        VARCHAR2(20) NOT NULL,
  ml_probability NUMBER(7,6)  CONSTRAINT chk_ml_prob CHECK (ml_probability BETWEEN 0 AND 1),
  ml_model       VARCHAR2(60),
  scored_at      DATE         DEFAULT SYSDATE NOT NULL
);
CREATE INDEX ix_score_band ON churn_scores (risk_band);
CREATE INDEX ix_score_segment ON churn_scores (segment);

CREATE TABLE ml_model_runs (
  run_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_ml_runs PRIMARY KEY,
  model_name  VARCHAR2(60) NOT NULL,
  trained_at  DATE         DEFAULT SYSDATE NOT NULL,
  n_train     NUMBER       NOT NULL,
  n_test      NUMBER       NOT NULL,
  accuracy    NUMBER(6,4),
  precision_  NUMBER(6,4),
  recall      NUMBER(6,4),
  f1          NUMBER(6,4),
  roc_auc     NUMBER(6,4),
  details     VARCHAR2(1000)
);

CREATE TABLE audit_log (
  audit_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_audit PRIMARY KEY,
  table_name  VARCHAR2(30)  NOT NULL,
  operation   VARCHAR2(20)  NOT NULL,
  record_key  VARCHAR2(40),
  old_value   VARCHAR2(400),
  new_value   VARCHAR2(400),
  changed_by  VARCHAR2(60)  DEFAULT SYS_CONTEXT('USERENV','SESSION_USER') NOT NULL,
  changed_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_audit_table ON audit_log (table_name, changed_at);

CREATE TABLE test_results (
  tc_id        VARCHAR2(10)  CONSTRAINT pk_test_results PRIMARY KEY,
  description  VARCHAR2(200) NOT NULL,
  input_text   VARCHAR2(300),
  expected     VARCHAR2(300),
  actual       VARCHAR2(400),
  status       VARCHAR2(6)   NOT NULL CONSTRAINT chk_test_status CHECK (status IN ('PASS','FAIL')),
  run_at       DATE          DEFAULT SYSDATE NOT NULL
);

