"""Generate sql/02_load_staging.sql from the Kaggle/IBM Telco churn CSV.
Customer names/e-mails are synthetic (the dataset is anonymised) and generated with a fixed seed."""
import csv, random, sys, os
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
src = os.path.join(root, 'data', 'telco.csv'); out = os.path.join(root, 'sql', '02_load_staging.sql')
random.seed(2770)
first = "Aarav Vivaan Aditya Arjun Rohan Karan Rahul Vikram Sanjay Amit Neha Priya Ananya Diya Kavya Isha Meera Pooja Riya Sneha James Emma Liam Olivia Noah Ava Lucas Mia Ethan Sofia Daniel Chloe Omar Layla Wei Mei Hiro Yuki Carlos Elena".split()
last = "Sharma Verma Iyer Nair Reddy Patel Gupta Singh Kumar Menon Rao Das Bose Kapoor Mehta Joshi Smith Johnson Brown Taylor Wilson Garcia Martinez Lopez Chen Wang Tanaka Kim Ali Khan Rossi Muller".split()
def q(s): return "'" + str(s).replace("'", "''") + "'"
rows = list(csv.DictReader(open(src, newline='', encoding='utf-8')))
cols = ["customerID","gender","SeniorCitizen","Partner","Dependents","tenure","PhoneService","MultipleLines","InternetService","OnlineSecurity","OnlineBackup","DeviceProtection","TechSupport","StreamingTV","StreamingMovies","Contract","PaperlessBilling","PaymentMethod","MonthlyCharges","TotalCharges","Churn"]
assert list(rows[0].keys()) == cols, rows[0].keys()
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write("-- Auto-generated by scripts/gen_staging.py from data/telco.csv (%d rows)\n" % len(rows))
    f.write("SET DEFINE OFF\nSET FEEDBACK OFF\nSET TERMOUT OFF\nTRUNCATE TABLE stg_telco;\n")
    for r in rows:
        nm = f"{random.choice(first)} {random.choice(last)}"
        em = f"{nm.lower().replace(' ', '.')}.{r['customerID'][:4].lower()}@retainai-demo.example"
        vals = [q(r[c].strip()) for c in cols] + [q(nm), q(em)]
        f.write("INSERT INTO stg_telco VALUES (" + ",".join(vals) + ");\n")
    f.write("COMMIT;\nSET TERMOUT ON\nSET FEEDBACK ON\nSELECT COUNT(*) AS staged_rows FROM stg_telco;\n")
print("wrote", out, len(rows))
